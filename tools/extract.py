#!/usr/bin/env python3
"""Pull every NIBHEX blob out of DIAM38.S and emit web/data.js.

Line ranges are 1-based inclusive line numbers in src/DIAM38.S (CRLF stripped).
Commented-out lines (leading '*') are skipped, so the beta-sign block is ignored.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = (ROOT / "src" / "DIAM38.S").read_text(encoding="latin-1").splitlines()

RANGES = {
    "levels":    (283, 736),
    "getReady":  (999, 1013),
    "bonus":     (1119, 1133),
    "noBonus":   (1162, 1176),
    "gameOver":  (1204, 1218),
    "lives":     (1303, 1307),
    "ball":      (2035, 2035),
    "dbMasks":   (2037, 2044),
    "cbMasks":   (2221, 2226),
    "key":       (2902, 2905),
    "score":     (3017, 3045),
    "levelNum":  (3190, 3206),
    "bricks":    (3746, 3761),
    "panel":     (4025, 4074),
    "menu":      (4103, 4168),
    "speed":     (4192, 4214),
    "help":      (4270, 4324),
    "entryGrob": (4489, 4495),
}

def blob(a, b):
    out = []
    for ln in SRC[a - 1:b]:
        if ln.lstrip().startswith("*") or not ln.strip():
            continue
        m = re.match(r"^\S*\s+NIBHEX\s+([0-9A-Fa-f]+)", ln)
        if m:
            out.append(m.group(1).upper())
    return "".join(out)

data = {k: blob(*v) for k, v in RANGES.items()}

expect = {
    "levels": 5 + 50 * 85, "getReady": 15 * 18, "bonus": 15 * 12, "noBonus": 15 * 16,
    "gameOver": 15 * 18, "lives": 35, "ball": 10, "dbMasks": 120, "cbMasks": 90,
    "key": 12, "score": 6 * 70, "levelNum": 6 * 40, "bricks": 16 * 18,
    "panel": 64 * 8, "menu": 58 * 24, "speed": 4 * 5 * 8, "help": 55 * 24,
    "entryGrob": 36 * 12,
}
bad = False
for k, n in expect.items():
    if len(data[k]) != n:
        print(f"LENGTH MISMATCH {k}: got {len(data[k])}, want {n}", file=sys.stderr)
        bad = True
if bad:
    sys.exit(1)

out = ROOT / "web" / "data.js"
out.parent.mkdir(exist_ok=True)
out.write_text(
    "// Generated by tools/extract.py from src/DIAM38.S -- do not edit by hand.\n"
    "// Nibble strings in memory order (first char = lowest address).\n"
    "const DIAMONDS_DATA = " + json.dumps(data, indent=1) + ";\n"
)
print(f"wrote {out} ({out.stat().st_size} bytes)")
